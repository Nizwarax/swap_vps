do_status(){
    local VIRT=$(detect_virt); local RAM=$(free -h | awk '/^Mem:/{print $2}'); local SWAP=$(free -h | awk '/^Swap:/{print $2 " / " $3}')
    echo -e "${CYAN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
    echo -e "${LIGHT}       ULTRA SWAP MANAGER v$VERSION${NC}"
    echo -e "${CYAN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
    echo -e " OS   : $(cat /etc/os-release 2>/dev/null | grep PRETTY_NAME | awk -F"\"" '{print $2}' || uname -s)"
    echo -e " Virt : $VIRT  |  FS: $(stat -f -c %T / 2>/dev/null || echo unknown) $(is_btrfs && echo '(BTRFS!)' || echo '')"
    echo -e " RAM  : $RAM  |  Swap: $SWAP"
    echo -e " Kernel swappiness: $(cat /proc/sys/vm/swappiness 2>/dev/null || echo ?)"
    echo -e "${CYAN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
    echo ""; free -h; echo ""; swapon --show 2>/dev/null || cat /proc/swaps; echo ""
    [ -f "$SYSCTL_CONF" ] && echo -e "${DIM}sysctl: $SYSCTL_CONF${NC}" && cat "$SYSCTL_CONF" | sed 's/^/  /'
    echo ""; systemctl is-active "$SERVICE" 2>/dev/null | grep -q active && echo -e "${GREEN}Service $SERVICE: active${NC}" || echo -e "${DIM}Service $SERVICE: inactive${NC}"
    [ -f /etc/fstab ] && echo -e "${DIM}fstab swap lines:${NC}" && grep -i swap /etc/fstab 2>/dev/null | sed 's/^/  /' || echo "  (none)"
}

