    local size_gb=${1:-}
    if [ -z "$size_gb" ]; then echo -e -n "${YELLOW}Enter swap size in GB (e.g. 2): ${NC}"; read size_gb; fi
    [[ ! "$size_gb" =~ ^[0-9]+$ ]] && { err "Invalid number: $size_gb"; return 1; }
    local free_mb=$(df -m / | awk 'NR==2{print $4}'); [ "$free_mb" -lt $((size_gb*1024+512)) ] && { err "Disk full! Free ${free_mb}MB need $((size_gb*1024))MB"; return 1; }
    info "Creating ${size_gb}GB swap file..."
    backup_fstab; swapoff "$SWAP_FILE" 2>/dev/null || true; rm -f "$SWAP_FILE"; safe_fstab_remove
    if ! create_swapfile_raw "$size_gb"; then
        warn "Swap file blocked -> trying ZRAM fallback..."
        if check_zram_support; then install_zram; else install_potato_fallback; fi
        return
    fi
    optimize_kernel "hdd"
    trap - INT TERM EXIT
    show_success_art "SWAP FILE ${size_gb}GB CREATED"
}

install_zram(){
    info "Enabling ZRAM..."
    if ! check_zram_support; then err "ZRAM not supported on this kernel"; install_potato_fallback; return; fi
    local ram_mb=$(get_ram_mb); local zram_mb
    if [ "$ram_mb" -lt 1024 ]; then zram_mb=$ram_mb; else zram_mb=$((ram_mb*60/100)); fi
    local algo="zstd"; grep -q zstd /sys/block/zram0/comp_algorithm 2>/dev/null && algo="zstd" || algo="lz4"
    [ "$ram_mb" -lt 1024 ] && algo="lz4"
    # reset if already has data
    swapoff /dev/zram0 2>/dev/null || true; echo 1 > /sys/block/zram0/reset 2>/dev/null || true
    echo "$algo" > /sys/block/zram0/comp_algorithm 2>/dev/null || true
    echo "${zram_mb}M" > /sys/block/zram0/disksize 2>/dev/null || echo $((zram_mb*1024*1024)) > /sys/block/zram0/disksize
    mkswap /dev/zram0; swapon -p 100 /dev/zram0
    if command -v systemctl >/dev/null 2>&1; then
        cat > /etc/systemd/system/$SERVICE <<SERV
[Unit]
Description=ZRAM Universal ULTRA v$VERSION
After=multi-user.target
[Service]
Type=oneshot
ExecStart=/bin/bash -c 'modprobe zram num_devices=1 && echo $algo > /sys/block/zram0/comp_algorithm 2>/dev/null; echo ${zram_mb}M > /sys/block/zram0/disksize; mkswap /dev/zram0 && swapon -p 100 /dev/zram0'
ExecStop=/bin/bash -c 'swapoff /dev/zram0 2>/dev/null || true; echo 1 > /sys/block/zram0/reset 2>/dev/null || true'
RemainAfterExit=yes
[Install]
WantedBy=multi-user.target
SERV
        systemctl daemon-reload; systemctl enable $SERVICE >/dev/null 2>&1 || true
    fi
    optimize_kernel "zram"
    trap - INT TERM EXIT
    show_success_art "ZRAM ${zram_mb}MB (${algo}) ENABLED"
}

install_hybrid(){
    info "Enabling ULTRA HYBRID (Recommended)..."
    local virt=$(detect_virt); local ram_mb=$(get_ram_mb); local ram_gb=$(get_ram_gb)
    local swap_ok=0; check_swap_support && swap_ok=1
    local zram_ok=0; check_zram_support && zram_ok=1
    local zram_mb; local disk_gb
    if [ "$ram_mb" -lt 1024 ]; then zram_mb=$ram_mb; disk_gb=1
    elif [ "$ram_mb" -lt 4096 ]; then zram_mb=$((ram_mb*60/100)); disk_gb=2
    else zram_mb=$((ram_mb*80/100)); disk_gb=4; fi

    if [ $swap_ok -eq 0 ] && [ $zram_ok -eq 0 ]; then info "Both blocked ($virt) -> Potato Optimizer..."; install_potato_fallback; return; fi
    if [ $swap_ok -eq 0 ]; then install_zram; return; fi
    if [ $zram_ok -eq 0 ]; then install_swapfile $disk_gb; return; fi

    info "Virt: $virt | RAM: ${ram_mb}MB -> ZRAM ${zram_mb}MB + Disk ${disk_gb}GB"
    backup_fstab
    swapoff -a 2>/dev/null || true; rm -f "$SWAP_FILE"; safe_fstab_remove
    systemctl stop $SERVICE 2>/dev/null || true; modprobe -r zram 2>/dev/null || true; modprobe zram num_devices=1

    local algo="zstd"; grep -q zstd /sys/block/zram0/comp_algorithm 2>/dev/null && algo="zstd" || algo="lz4"
    [ "$ram_mb" -lt 1024 ] && algo="lz4"
    echo "$algo" > /sys/block/zram0/comp_algorithm 2>/dev/null || true
    echo "${zram_mb}M" > /sys/block/zram0/disksize; mkswap /dev/zram0; swapon -p 100 /dev/zram0

    if ! create_swapfile_raw "$disk_gb" 10; then
        warn "Disk swap failed mid-hybrid, keeping ZRAM only"
        safe_fstab_remove
    fi

    cat > /etc/systemd/system/$SERVICE <<SERV
[Unit]
Description=ZRAM Hybrid ULTRA v$VERSION
After=multi-user.target
[Service]
Type=oneshot
ExecStart=/bin/bash -c 'modprobe zram num_devices=1 && echo $algo > /sys/block/zram0/comp_algorithm 2>/dev/null; echo ${zram_mb}M > /sys/block/zram0/disksize; mkswap /dev/zram0 && swapon -p 100 /dev/zram0; swapon -p 10 $SWAP_FILE 2>/dev/null || true'
ExecStop=/bin/bash -c 'swapoff $SWAP_FILE 2>/dev/null || true; swapoff /dev/zram0 2>/dev/null || true; echo 1 > /sys/block/zram0/reset 2>/dev/null || true'
RemainAfterExit=yes
[Install]
WantedBy=multi-user.target
SERV
    systemctl daemon-reload 2>/dev/null; systemctl enable $SERVICE >/dev/null 2>&1 || true
    optimize_kernel "hybrid"
    trap - INT TERM EXIT
    show_success_art "ULTRA HYBRID ENABLED - ZRAM ${zram_mb}MB + DISK ${disk_gb}GB"
}

install_potato_fallback(){
    info "Potato Mode - Low RAM / OpenVZ Optimizer..."
    if [ -f /etc/debian_version ]; then
        apt update -qq && apt install -y -qq earlyoom 2>/dev/null && systemctl enable earlyoom 2>/dev/null && systemctl start earlyoom 2>/dev/null || true
    elif [ -f /etc/redhat-release ]; then
        yum install -y earlyoom 2>/dev/null; systemctl enable earlyoom 2>/dev/null; systemctl start earlyoom 2>/dev/null || true
    fi
    optimize_kernel "potato"
    trap - INT TERM EXIT
    show_success_art "POTATO MODE ACTIVE - Kernel Tuned + EarlyOOM"
}

remove_all(){
    info "Removing all swap..."
    backup_fstab
    swapoff -a 2>/dev/null || true; rm -f "$SWAP_FILE"; safe_fstab_remove
    systemctl stop $SERVICE 2>/dev/null || true; systemctl disable $SERVICE 2>/dev/null || true
    rm -f /etc/systemd/system/$SERVICE; systemctl daemon-reload 2>/dev/null || true
    modprobe -r zram 2>/dev/null || true; echo 1 > /sys/block/zram0/reset 2>/dev/null || true
    rm -f "$SYSCTL_CONF"; sysctl --system >/dev/null 2>&1 || true
    # full cleanup earlyoom only if we installed it
    if systemctl is-active earlyoom >/dev/null 2>&1; then
        warn "earlyoom still active (potato) - stopping..."
        systemctl stop earlyoom 2>/dev/null || true; systemctl disable earlyoom 2>/dev/null || true
    fi
    [ -f /etc/debian_version ] && apt remove -y -qq zram-tools 2>/dev/null || true
    trap - INT TERM EXIT
    show_success_art "ALL SWAP REMOVED"
}

print_help(){
    cat <<HELP
${CYAN}ULTRA SWAP MANAGER v$VERSION${NC}
Usage: swap [COMMAND] [ARGS]

Commands:
  create <GB>   Create swap file (e.g. swap create 2)
  zram          Enable ZRAM only
  hybrid        Enable ULTRA HYBRID (ZRAM+Disk) - recommended
  remove        Remove all swap
  status        Show detail status (no clear)
  help          Show this help
  (no args)     Interactive menu

Examples:
  swap status
  swap create 4
  swap hybrid
  swap remove

Log: $LOG  |  Config: $SYSCTL_CONF  |  Service: $SERVICE
HELP
}

# ── CLI dispatcher ──
case "${1:-menu}" in
    create) install_swapfile "${2:-}" ;;
    zram) install_zram ;;
    hybrid) install_hybrid ;;
    remove|rm|delete) remove_all ;;
    status|st|info) do_status ;;
    help|--help|-h) print_help ;;
    --version|-v|version) echo "ULTRA SWAP MANAGER v$VERSION" ;;
    menu) while true; do
        display_menu; read choice
        case $choice in
            1) install_swapfile; read -p "Press Enter..." ;;
            2) install_zram; read -p "Press Enter..." ;;
            3) install_hybrid; read -p "Press Enter..." ;;
            4) remove_all; read -p "Press Enter..." ;;
            5) do_status; read -p "Press Enter..." ;;
            6) clear; echo -e "${GREEN}Done. - Deki Niswara v$VERSION${NC}"; trap - INT TERM EXIT; exit 0 ;;
            *) err "Invalid!"; sleep 1 ;;
        esac
    done ;;
    *) err "Unknown command: $1"; print_help; exit 1 ;;
esac
trap - INT TERM EXIT
