detect_virt(){
    [ -f /proc/user_beancounters ] && { echo "openvz"; return; }
    [ -f /proc/vz/veinfo ] && { echo "openvz"; return; }
    if command -v systemd-detect-virt >/dev/null 2>&1; then
        V=$(systemd-detect-virt 2>/dev/null); [ -n "$V" ] && [ "$V" != "none" ] && { echo "$V"; return; }
    fi
    grep -q "lxc" /proc/1/cgroup 2>/dev/null && { echo "lxc"; return; }
    echo "kvm"
}
get_ram_mb(){ free -m | awk '/^Mem:/{print $2}'; }
get_ram_gb(){ local g=$(free -g | awk '/^Mem:/{print $2}'); [ "$g" -eq 0 ] && echo 1 || echo "$g"; }
is_btrfs(){ stat -f -c %T / 2>/dev/null | grep -qi btrfs || grep -q " btrfs " /proc/mounts 2>/dev/null; }

backup_fstab(){
    cp -a /etc/fstab "/etc/fstab.bak.$(date +%s)" 2>/dev/null || true
    cp -a "$SYSCTL_CONF" "${SYSCTL_CONF}.bak.$(date +%s)" 2>/dev/null || true
}
safe_fstab_remove(){
    # ONLY remove our /swapfile line, never generic "swap"
    sed -i "\#^${SWAP_FILE}[[:space:]]#d" /etc/fstab 2>/dev/null || true
}
safe_fstab_add(){
    local pri="$1"
    safe_fstab_remove
    if [ -n "$pri" ]; then
        echo "$SWAP_FILE none swap sw,pri=$pri 0 0" >> /etc/fstab
    else
        echo "$SWAP_FILE none swap sw 0 0" >> /etc/fstab
    fi
}

check_swap_support(){
    local f="/tmp/.swaptest_$$"
    if is_btrfs; then return 1; fi
    fallocate -l 64M "$f" 2>/dev/null || dd if=/dev/zero of="$f" bs=1M count=64 >/dev/null 2>&1
    chmod 600 "$f" 2>/dev/null; mkswap "$f" >/dev/null 2>&1
    if swapon "$f" >/dev/null 2>&1; then swapoff "$f" 2>/dev/null; rm -f "$f"; return 0
    else rm -f "$f"; return 1; fi
}
check_zram_support(){
    modprobe zram num_devices=1 >/dev/null 2>&1
    [ -d /sys/block/zram0 ] && return 0 || return 1
}

optimize_kernel(){
    local mode=$1; local ram=$(get_ram_mb); mkdir -p /etc/sysctl.d
    backup_fstab
    cat > "$SYSCTL_CONF" <<EOF
# Generated by ULTRA SWAP MANAGER v$VERSION - $mode - $(date -Iseconds)
vm.vfs_cache_pressure=50
vm.dirty_ratio=15
vm.dirty_background_ratio=5
vm.page-cluster=0
vm.overcommit_memory=1
vm.watermark_scale_factor=200
EOF
    if [ "$ram" -lt 1024 ]; then
        echo "vm.swappiness=5" >> "$SYSCTL_CONF"
        echo "vm.oom_kill_allocating_task=1" >> "$SYSCTL_CONF"
    else
        [[ "$mode" == "zram" ]] && echo "vm.swappiness=100" >> "$SYSCTL_CONF" || echo "vm.swappiness=10" >> "$SYSCTL_CONF"
    fi
    modprobe tcp_bbr >/dev/null 2>&1 && { echo "net.core.default_qdisc=fq" >> "$SYSCTL_CONF"; echo "net.ipv4.tcp_congestion_control=bbr" >> "$SYSCTL_CONF"; }
    sysctl --system >/dev/null 2>&1 || sysctl -p "$SYSCTL_CONF" >/dev/null 2>&1 || true
    ok "Kernel tuned [$mode] swappiness=$(grep swappiness $SYSCTL_CONF | awk -F"\"" '{print $2}')"
}

create_swapfile_raw(){
    local size_gb=$1; local pri=${2:-""}
    if is_btrfs; then
        warn "BTRFS detected -> using dd + chattr +C (no fallocate/hole)"
        rm -f "$SWAP_FILE"; touch "$SWAP_FILE"; chattr +C "$SWAP_FILE" 2>/dev/null || true
        dd if=/dev/zero of="$SWAP_FILE" bs=1M count=$((size_gb*1024)) status=progress
    else
        fallocate -l "${size_gb}G" "$SWAP_FILE" 2>/dev/null || dd if=/dev/zero of="$SWAP_FILE" bs=1M count=$((size_gb*1024)) status=progress
    fi
    chmod 600 "$SWAP_FILE"; mkswap "$SWAP_FILE"
    if ! swapon ${pri:+-p $pri} "$SWAP_FILE" 2>/dev/null; then
        err "swapon blocked on this VPS ($(detect_virt))"
        rm -f "$SWAP_FILE"; return 1
    fi
    if [ -n "$pri" ]; then safe_fstab_add "$pri"; else safe_fstab_add ""; fi
    return 0
}

